#!/usr/bin/env python3
"""
optimize_astro_site.py

Scaffolds the astro/ static HTML tutorial site to match Ray's standard course
layout (cf. course_template, python_intro):

  - Generates a shared stylesheet (styles/styles.css) with CSS custom properties
    for light/dark theming.
  - Generates js/theme.js (toggle + persisted preference + system default).
  - Generates js/nav.js (prev/next navigation, page order edited by hand).
  - Injects a sticky header into every HTML page with:
      [ Site title ] ............ [ Ray's House of Fun | 🌙 ]
  - Wires up the shared stylesheet and scripts in every page <head>.
  - Adds a <nav id="page-nav"> placeholder at the bottom of <main>.

Idempotent: re-running only touches files that actually need to change. A
`<meta name="scaffold-version">` tag in each processed page records the version
so future runs can detect and upgrade in place.

Usage:
    python3 optimize_astro_site.py                    # operate on cwd
    python3 optimize_astro_site.py --project-root .   # explicit
    python3 optimize_astro_site.py --dry-run          # show changes only
    python3 optimize_astro_site.py --no-backup        # skip .bak files

Dependencies:
    pip install beautifulsoup4
"""

