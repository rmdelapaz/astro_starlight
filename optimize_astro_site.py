# ---------------------------------------------------------------------------
# HTML helpers
# ---------------------------------------------------------------------------

def header_markup():
    return (
        '<header class="site-header" data-scaffold="header">\n'
        '  <div class="site-header__inner">\n'
        f'    <a href="index.html" class="site-header__title">{SITE_TITLE}</a>\n'
        '    <nav class="site-header__nav">\n'
        f'      <a href="{HUB_URL}" class="site-header__hub-link">{HUB_LABEL}</a>\n'
        '      <button id="theme-toggle" class="theme-toggle" type="button" '
        'aria-label="Toggle theme">🌙</button>\n'
        '    </nav>\n'
        '  </div>\n'
        '</header>'
    )


def page_nav_markup():
    return '<nav class="page-nav" id="page-nav" data-scaffold="page-nav"></nav>'


def rel_path(html_file: Path, asset_path: Path) -> str:
    rel = os.path.relpath(asset_path, html_file.parent)
    return rel.replace(os.sep, "/")


def ensure_head(soup: BeautifulSoup):
    head = soup.find("head")
    if head is not None:
        return head
    html = soup.find("html")
    if html is None:
        html = soup.new_tag("html")
        for child in list(soup.children):
            html.append(child.extract())
        soup.append(html)
    head = soup.new_tag("head")
    html.insert(0, head)
    return head


def ensure_body(soup: BeautifulSoup):
    body = soup.find("body")
    if body is not None:
        return body
    html = soup.find("html") or soup
    body = soup.new_tag("body")
    html.append(body)
    return body


def ensure_link(soup, head, href: str) -> bool:
    for link in head.find_all("link"):
        if link.get("href") == href and "stylesheet" in (link.get("rel") or []):
            return False
    tag = soup.new_tag("link", rel="stylesheet", href=href)
    head.append(tag)
    return True


def ensure_script(soup, head, src: str, defer: bool = True) -> bool:
    for script in head.find_all("script"):
        if script.get("src") == src:
            if defer and not script.has_attr("defer"):
                script["defer"] = ""
                return True
            return False
    tag = soup.new_tag("script", src=src)
    if defer:
        tag["defer"] = ""
    head.append(tag)
    return True


def replace_or_insert_header(soup, body) -> bool:
    new_header = BeautifulSoup(header_markup(), "html.parser").find("header")
    existing = body.find("header", attrs={"data-scaffold": "header"})
    if existing:
        if str(existing) == str(new_header):
            return False
        existing.replace_with(new_header)
        return True
    body.insert(0, new_header)
    return True


def ensure_page_nav(soup, body) -> bool:
    existing = body.find("nav", attrs={"data-scaffold": "page-nav"})
    if existing:
        return False
    new_nav = BeautifulSoup(page_nav_markup(), "html.parser").find("nav")
    main = body.find("main")
    (main or body).append(new_nav)
    return True


def mark_scaffolded(soup, head) -> bool:
    existing = head.find("meta", attrs={"name": SCAFFOLD_META_NAME})
    if existing:
        if existing.get("content") == SCAFFOLD_VERSION:
            return False
        existing["content"] = SCAFFOLD_VERSION
        return True
    meta = soup.new_tag("meta")
    meta.attrs["name"] = SCAFFOLD_META_NAME
    meta.attrs["content"] = SCAFFOLD_VERSION
    head.append(meta)
    return True


# ---------------------------------------------------------------------------
# File operations
# ---------------------------------------------------------------------------

def write_if_changed(path: Path, content: str, backup: bool, dry_run: bool) -> str:
    if path.exists():
        existing = path.read_text(encoding="utf-8")
        if existing == content:
            return "unchanged"
        if not dry_run:
            if backup:
                shutil.copy2(path, path.with_suffix(path.suffix + ".bak"))
            path.write_text(content, encoding="utf-8")
        return "updated"
    if not dry_run:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
    return "created"


def process_html_file(path: Path, project_root: Path,
                      backup: bool, dry_run: bool):
    notes: list[str] = []
    try:
        raw = path.read_text(encoding="utf-8")
    except UnicodeDecodeError:
        return "skipped", [f"could not decode {path.name} as UTF-8"]

    soup = BeautifulSoup(raw, "html.parser")

    head = ensure_head(soup)
    body = ensure_body(soup)

    css_rel = rel_path(path, project_root / CSS_REL)
    theme_js_rel = rel_path(path, project_root / THEME_JS_REL)
    nav_js_rel = rel_path(path, project_root / NAV_JS_REL)

    ensure_link(soup, head, css_rel)
    ensure_script(soup, head, theme_js_rel, defer=True)
    ensure_script(soup, head, nav_js_rel, defer=True)
    replace_or_insert_header(soup, body)
    ensure_page_nav(soup, body)
    mark_scaffolded(soup, head)

    inline_styles = soup.find_all("style")
    if inline_styles:
        notes.append(f"{len(inline_styles)} inline <style> block(s) preserved "
                     f"(may conflict with shared stylesheet)")

    new_content = str(soup)
    if new_content == raw:
        return "unchanged", notes

    if not dry_run:
        if backup:
            shutil.copy2(path, path.with_suffix(path.suffix + ".bak"))
        path.write_text(new_content, encoding="utf-8")
    return "updated", notes


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def discover_html(project_root: Path) -> list[Path]:
    found: list[Path] = []
    for path in sorted(project_root.rglob("*.html")):
        rel = path.relative_to(project_root)
        if any(part in {"styles", "js", "assets", "node_modules", ".git", "_backup"}
               for part in rel.parts):
            continue
        if path.name in SKIP_NAMES:
            continue
        found.append(path)
    return found


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Scaffold the astro/ HTML tutorial site "
                    "(shared CSS, dark/light toggle, header, prev/next)."
    )
    parser.add_argument("--project-root", type=Path, default=Path.cwd())
    parser.add_argument("--dry-run", action="store_true")
    parser.add_argument("--no-backup", action="store_true")
    args = parser.parse_args()

    project_root = args.project_root.resolve()
    backup = not args.no_backup
    dry_run = args.dry_run

    if not project_root.is_dir():
        sys.stderr.write(f"Not a directory: {project_root}\n")
        return 2

    mode = "DRY-RUN" if dry_run else "APPLY"
    print(f"\n=== optimize_astro_site.py  [{mode}] ===")
    print(f"Project root:  {project_root}")
    print(f"Backups:       {'on (.bak)' if backup else 'off'}")
    print(f"Scaffold ver:  {SCAFFOLD_VERSION}\n")

    print("Assets:")
    asset_results = {
        CSS_REL:      write_if_changed(project_root / CSS_REL,
                                       CSS_CONTENT, backup, dry_run),
        THEME_JS_REL: write_if_changed(project_root / THEME_JS_REL,
                                       THEME_JS_CONTENT, backup, dry_run),
        NAV_JS_REL:   write_if_changed(project_root / NAV_JS_REL,
                                       NAV_JS_CONTENT, backup, dry_run),
    }
    for rel, status in asset_results.items():
        print(f"  [{status:9s}] {rel}")

    html_files = discover_html(project_root)
    print(f"\nHTML files ({len(html_files)} found):")
    if not html_files:
        print("  (none — nothing to scaffold)")

    counts = {"updated": 0, "unchanged": 0, "skipped": 0}
    all_notes: list[tuple[str, str]] = []

    for path in html_files:
        rel = path.relative_to(project_root)
        status, notes = process_html_file(path, project_root, backup, dry_run)
        counts[status] = counts.get(status, 0) + 1
        print(f"  [{status:9s}] {rel}")
        for n in notes:
            all_notes.append((str(rel), n))

    print("\nSummary:")
    print(f"  Assets:   "
          f"{sum(1 for s in asset_results.values() if s == 'created'):>3} created, "
          f"{sum(1 for s in asset_results.values() if s == 'updated'):>3} updated, "
          f"{sum(1 for s in asset_results.values() if s == 'unchanged'):>3} unchanged")
    print(f"  HTML:     "
          f"{counts.get('updated', 0):>3} updated, "
          f"{counts.get('unchanged', 0):>3} unchanged, "
          f"{counts.get('skipped', 0):>3} skipped")

    if all_notes:
        print("\nNotes:")
        for file_rel, note in all_notes:
            print(f"  · {file_rel}: {note}")

    if dry_run:
        print("\n(dry-run — no files were written)")
    else:
        print("\nNext step: open js/nav.js and fill in the PAGES array "
              "with your lesson order.")

    return 0


if __name__ == "__main__":
    sys.exit(main())
